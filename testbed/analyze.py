#!/usr/bin/env python3
"""Turn reports/testbed_results.json into reports/testbed_report.md + fig6_testbed.png."""
import json, sys
from pathlib import Path
import numpy as np
from scipy.stats import wilcoxon
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parents[1]
D = json.loads((ROOT / "reports" / "testbed_results.json").read_text())
LAB = {"adaptive": "CADA-AASM", "static_t5": "Static T5", "static_t3": "Static T3",
       "adaptive_batch": "CADA + batch-sign", "static_t5_batch": "Static T5 + batch-sign"}

def col(rows, cfg, key): return np.array([r["summary"][key] for r in rows if r["config"] == cfg])
def ms(x): return f"{x.mean():.3f} ± {x.std(ddof=1) if len(x) > 1 else 0:.3f}"
def pw(a, b):
    d = a - b
    if len(d) < 2 or np.allclose(d, 0): return "n/a (identical)"
    try: return f"{wilcoxon(a, b).pvalue:.3f}"
    except Exception: return "n/a"

A, B, M = D["partA"], D["partB"], D["meta"]
L = ["# Real-link testbed report (netns + kernel tbf shaping)\n",
     "Generated by `testbed/analyze.py` from `reports/testbed_results.json`. **Read the scope box first.**\n",
     "> **Scope.** REAL: two network namespaces + veth, kernel tbf bandwidth shaping (both directions, "
     f"{M['queue_ms']:.0f} ms queue; tail-drop => real TCP loss/retransmit when the queue overflows), real TCP, the project's real packet bytes, "
     "echo-probe RTT over the shaped link, host CPU under real busy-loop load. "
     "EMULATED/OMITTED: kernel netem is unavailable here, so propagation delay is a stated per-phase *receiver hold*, "
     "random packet loss is not modelled, PQ compute is not charged to latency (native cost: see `native_pqc_bench.json`). "
     f"{M['nproc']} CPU cores; pure-Python PQ code was used only to *generate* packet bytes.\n",
     "## Phases (same as the emulated evaluation's staged stress)\n", "| phase | link | receiver hold (ms) | busy-loop procs |", "|---|---|---|---|"]
for k, v in M["phases"].items():
    L.append(f"| {k} | {'unshaped' if v['bw_mbps'] is None else str(v['bw_mbps']) + ' Mbit/s'} | {v['hold_ms']} | {v['busy_procs']} |")
reps = len({r['rep'] for r in A})
L += [f"\n## Part A: staged stress, {reps} repetitions per configuration\n",
      "| config | SLA viol. clinical (stress) | SLA viol. research (stress) | p95 clinical ms | tier changes | min clinical tier | mean wire B (clinical) |", "|---|---|---|---|---|---|---|"]
for c in LAB:
    if not any(r["config"] == c for r in A): continue
    L.append(f"| {LAB[c]} | {ms(col(A,c,'viol_clinical_stress'))} | {ms(col(A,c,'viol_research_stress'))} | {ms(col(A,c,'p95_clinical'))} | "
             f"{col(A,c,'tier_changes').mean():.1f} | {int(col(A,c,'min_clinical_tier').min())} | {col(A,c,'mean_wire_clinical').mean():.0f} |")
L += ["\nPaired Wilcoxon (p) on per-rep p95 research latency: " +
      "; ".join(f"CADA vs {LAB[o]}: {pw(col(A,'adaptive','p95_research'), col(A,o,'p95_research'))}" for o in ("static_t5", "static_t3") if any(r['config']==o for r in A)) + "\n"]
bws = sorted({r["bw"] for r in B}, reverse=True)
L += ["## Part B: constant severe stress (150 ms hold + 2 busy procs), vary link bandwidth\n",
      "Cell = clinical-path SLA-violation rate over all cycles (mean over reps). Lower is better.\n",
      "| bandwidth | " + " | ".join(LAB[c] for c in ("adaptive", "static_t5", "static_t3")) + " |", "|---|---|---|---|"]
sw = {}
for bw in bws:
    row = []
    for c in ("adaptive", "static_t5", "static_t3"):
        v = np.array([r["viol"] for r in B if r["bw"] == bw and r["config"] == c]); sw[(bw, c)] = v
        row.append(f"{100*v.mean():.1f} %")
    L.append(f"| {bw:g} Mbit/s | " + " | ".join(row) + " |")
L += ["\nPaired Wilcoxon (CADA vs static T5) per bandwidth: " + "; ".join(f"{bw:g} Mbit/s p={pw(sw[(bw,'adaptive')], sw[(bw,'static_t5')])}" for bw in bws) + "\n"]
nat = ROOT / "reports" / "native_pqc_bench.json"
if nat.exists():
    N = json.loads(nat.read_text())
    L += [f"## Native crypto cost (liboqs {N['liboqs']}, median of {N['n']} calls, ms)\n",
          "| primitive | pk B | ct/sig B | keygen/sign | encaps/verify | decaps |", "|---|---|---|---|---|---|"]
    for k, v in N["kem"].items():
        L.append(f"| {k} | {v['pk']} | {v['ct']} | {v['keygen']['median_ms']} | {v['encaps']['median_ms']} | {v['decaps']['median_ms']} |")
    for k, v in N["sig"].items():
        L.append(f"| {k} | {v['pk']} | {v['sig']} | {v['sign']['median_ms']} | {v['verify']['median_ms']} | - |")
    L += ["", "The pure-Python reference code used elsewhere in this project measured ~94 ms per ML-DSA-65 sign. Native signing is ~0.1 ms, i.e. roughly three orders of magnitude cheaper, so excluding PQ compute from per-packet latency is justified on a native stack and **wire size is the cost that matters**.\n"]
L += ["## Reading (what these numbers do and do not show)\n",
      "* **Staged stress (Part A):** on a real shaped link no configuration violated the 200 ms SLA. Static T5 had ~5.6 ms higher p95 latency than CADA or static T3; with batch signing all three are equal. The controller did react to *real* RTT and *real* CPU load (tier changes 3 per trial, clinical floor held: minimum clinical tier 3 in every trial).",
      "* **Constrained link (Part B):** the effect of packet size appears only at or below ~1 Mbit/s. At 0.5 Mbit/s static T5 violated the SLA on every cycle, CADA on a minority of cycles (it starts at T5 and needs 3 consecutive cycles plus a re-key before dropping), and **static T3 on none**. At 1 Mbit/s CADA was slightly *worse* than both statics (the transition cost).",
      "* **Consequence:** the headline benefit of the emulated evaluation (7.4% -> 4.1% violations vs static T5) is **not reproduced on a real link at >= 2 Mbit/s** - there the emulator's fragment-queueing and loss terms, not the wire bytes alone, drove violations. What the real link supports: (i) adaptation avoids the catastrophic failure of static T5 on very thin links, (ii) a well-chosen static T3 is as good or better on latency, (iii) the remaining value of CADA is joint privacy/crypto adaptation under a floor and higher protection when the budget allows.",
      f"* **Statistics:** {reps} repetitions per cell; with n=4 pairs the smallest attainable two-sided Wilcoxon p is 0.125, so no difference here can reach p<0.05. These are descriptive results, not significance tests.",
      "* **Method note:** a first full run used a 16 KB token bucket and was discarded after we noticed latency equalled the injected hold at every bandwidth (the bucket let 5 KB packets cross at line rate, so the link never bound). The shaper now uses a ~1 MTU bucket; a single-message check shows ~72% of ideal serialization time (the first MTU crosses free).",
      "* **Not covered:** random packet loss and netem-style delay (unavailable kernel module), multi-hop paths, other traffic, native TLS stack, constrained-device hardware.\n"]
open(ROOT / "reports" / "testbed_report.md", "w").write("\n".join(L))

fig, ax = plt.subplots(1, 2, figsize=(11, 3.8))
x = np.arange(len(bws)); w = 0.27
for i, c in enumerate(("adaptive", "static_t5", "static_t3")):
    ax[0].bar(x + (i - 1) * w, [100 * sw[(b, c)].mean() for b in bws], w, label=LAB[c],
              yerr=[100 * (sw[(b, c)].std(ddof=1) if len(sw[(b, c)]) > 1 else 0) for b in bws], capsize=2)
ax[0].set_xticks(x); ax[0].set_xticklabels([f"{b:g}" for b in bws]); ax[0].set_xlabel("link bandwidth (Mbit/s)")
ax[0].set_ylabel("clinical SLA violations (%)"); ax[0].set_title("Real link, constant severe stress"); ax[0].legend(fontsize=8)
for c in ("adaptive", "static_t5", "static_t3"):
    rs = [r for r in A if r["config"] == c]
    if not rs: continue
    m = np.median([[x_["lat_research"] for x_ in r["rows"]] for r in rs], axis=0)
    ax[1].plot(m, label=LAB[c])
ax[1].axhline(200, ls="--", c="grey", lw=1); ax[1].set_xlabel("control cycle"); ax[1].set_ylabel("research latency, median (ms)")
ax[1].set_title("Real link, staged stress"); ax[1].legend(fontsize=8)
plt.tight_layout(); plt.savefig(ROOT / "reports" / "fig6_testbed.png", dpi=150)
print("\n".join(L))
